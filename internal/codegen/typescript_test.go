package codegen

import (
	"os"
	"strings"
	"testing"

	_ "github.com/acme/ontology/internal/expr"
	"github.com/acme/ontology/internal/spec"
)

func example(t *testing.T) *spec.CompiledOntology {
	t.Helper()
	files, ld := spec.LoadFS(os.DirFS("../../examples/ontology"), "examples/ontology")
	ont, cd := spec.Compile(files)
	if d := append(ld, cd...); d.HasErrors(false) {
		t.Fatalf("example: %v", d.Codes())
	}
	ont.Version = 7
	return ont
}

func generate(t *testing.T) string {
	t.Helper()
	out, err := TypeScript(example(t), Options{Header: "commit abc"})
	if err != nil {
		t.Fatal(err)
	}
	return string(out)
}

func TestTypeScriptTypes(t *testing.T) {
	ts := generate(t)
	for _, want := range []string{
		"// Code generated by ontoctl sdk generate; DO NOT EDIT.",
		"// commit abc",
		`export const ONTOLOGY = "mro";`,
		"export const ONTOLOGY_VERSION = 7;",
		// enum from a value type, enum from inline constraints, decimal as string, array element type
		`status: "OPEN" | "IN_PROGRESS" | "DONE" | "CANCELLED" | null;`,
		`status: "ACTIVE" | "GROUNDED" | null;`,
		"estimatedCost: string | null;",
		"certifications: string[] | null;",
		"priority: number | null;",
		"CONFIDENTIAL: null when your clearance is lower.",
		// links
		`export type WorkOrderLink = "aircraft" | "technician";`,
		`export type AircraftLink = "parts" | "workOrders";`,
		`export type WorkOrder = OntologyObject<"WorkOrder", WorkOrderProperties>;`,
		// actions: required vs optional, objectRef as PK
		"export interface AssignWorkOrderParams {",
		"  workOrder: PK;",
		"  note?: string;",
		"export interface GroundAircraftParams {",
		"Precondition: 只有 OPEN 状态的工单可以指派",
		// client wiring
		`WorkOrder: new ObjectSet<"WorkOrder", WorkOrderProperties, WorkOrderLink>(t, "WorkOrder"),`,
		"assignWorkOrder: new Action<AssignWorkOrderParams>(t, \"assignWorkOrder\"),",
		"export function createClient(options: ClientOptions): OntologyClient {",
	} {
		if !strings.Contains(ts, want) {
			t.Errorf("generated SDK lacks:\n  %s", want)
		}
	}
	if strings.Contains(ts, "descriptionEmbedding") {
		t.Error("vector properties are not returned by the query service and must not be typed")
	}
	if strings.Contains(ts, "\t") {
		t.Error("generated TypeScript should be space-indented")
	}
}

func TestTypeScriptDeterministic(t *testing.T) {
	if generate(t) != generate(t) {
		t.Error("generation must be deterministic")
	}
}

func TestNamesAreSanitized(t *testing.T) {
	if typeName("delete") != "T_delete" || typeName("WorkOrder") != "WorkOrder" {
		t.Errorf("typeName: %q %q", typeName("delete"), typeName("WorkOrder"))
	}
	if key("tail-no") != `"tail-no"` || key("tailNo") != "tailNo" {
		t.Errorf("key: %q %q", key("tail-no"), key("tailNo"))
	}
}
