// Package codegen generates typed client SDKs from a compiled ontology.
package codegen

import (
	"bytes"
	_ "embed"
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/acme/ontology/internal/spec"
)

//go:embed runtime.ts
var runtimeTS string

// Options controls generation.
type Options struct {
	// Header is a free-form line added to the file comment (e.g. the source commit).
	Header string
}

var reIdent = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// tsReserved lists identifiers that cannot be used as TypeScript type or member names.
var tsReserved = func() map[string]bool {
	m := map[string]bool{}
	for _, w := range strings.Fields("break case catch class const continue debugger default delete do else enum export extends false finally for function if import in instanceof new null return super switch this throw true try typeof var void while with") {
		m[w] = true
	}
	return m
}()

func quote(s string) string { return strconv.Quote(s) } // Go and JSON/TS escaping agree for the strings we emit

// key renders an object property key, quoting it when it is not a plain identifier.
func key(s string) string {
	if reIdent.MatchString(s) {
		return s
	}
	return quote(s)
}

func typeName(apiName string) string {
	n := apiName
	if !reIdent.MatchString(n) || tsReserved[n] {
		n = "T_" + regexp.MustCompile(`[^A-Za-z0-9_$]`).ReplaceAllString(n, "_")
	}
	return n
}

func union(values []string) string {
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = quote(v)
	}
	return strings.Join(parts, " | ")
}

// tsType maps a property or parameter base type to TypeScript. Decimals are strings (exact),
// dates/timestamps are ISO strings, arrays/structs are JSON.
func tsType(ont *spec.CompiledOntology, t spec.TypeRef, c spec.Constraints, valueType string) string {
	if len(c.Enum) == 0 && valueType != "" {
		if vt := ont.ValueTypes[valueType]; vt != nil {
			c = vt.Constraints
		}
	}
	switch t.Base {
	case spec.TString:
		if len(c.Enum) > 0 {
			return union(c.Enum)
		}
		return "string"
	case spec.TInteger, spec.TLong:
		if len(c.Enum) > 0 {
			return strings.Join(c.Enum, " | ")
		}
		return "number"
	case spec.TDouble:
		return "number"
	case spec.TDecimal, spec.TDate, spec.TTimestamp, spec.TAttachment:
		return "string"
	case spec.TBoolean:
		return "boolean"
	case spec.TGeoPoint:
		return "{ lat: number; lon: number }"
	case spec.TArray:
		if t.Elem != nil {
			el := tsType(ont, *t.Elem, spec.Constraints{}, "")
			if strings.Contains(el, "|") || strings.Contains(el, "{") {
				el = "(" + el + ")"
			}
			return el + "[]"
		}
		return "unknown[]"
	case spec.TVector:
		return "number[]"
	}
	return "unknown"
}

func doc(b *bytes.Buffer, indent string, lines ...string) {
	var keep []string
	for _, l := range lines {
		if l = strings.TrimSpace(strings.ReplaceAll(l, "*/", "* /")); l != "" {
			keep = append(keep, l)
		}
	}
	if len(keep) == 0 {
		return
	}
	if len(keep) == 1 {
		fmt.Fprintf(b, "%s/** %s */\n", indent, keep[0])
		return
	}
	fmt.Fprintf(b, "%s/**\n", indent)
	for _, l := range keep {
		fmt.Fprintf(b, "%s * %s\n", indent, l)
	}
	fmt.Fprintf(b, "%s */\n", indent)
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// TypeScript renders a single self-contained TypeScript module for the ontology.
func TypeScript(ont *spec.CompiledOntology, opts Options) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by ontoctl sdk generate; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Ontology %q version %d, checksum %s.\n", ont.APIName, ont.Version, ont.Checksum)
	if opts.Header != "" {
		fmt.Fprintf(&b, "// %s\n", strings.ReplaceAll(opts.Header, "\n", " "))
	}
	b.WriteString("/* eslint-disable */\n\n")
	b.WriteString(runtimeTS)

	b.WriteString("\n// ---------------------------------------------------------------------------\n")
	b.WriteString("// Ontology types\n")
	b.WriteString("// ---------------------------------------------------------------------------\n\n")
	fmt.Fprintf(&b, "export const ONTOLOGY = %s;\nexport const ONTOLOGY_VERSION = %d;\nexport const ONTOLOGY_CHECKSUM = %s;\n\n",
		quote(ont.APIName), ont.Version, quote(ont.Checksum))

	seen := map[string]string{}
	types := sortedKeys(ont.ObjectTypes)
	for _, name := range types {
		tn := typeName(name)
		if prev, dup := seen[tn]; dup {
			return nil, fmt.Errorf("object types %q and %q map to the same TypeScript name %q", prev, name, tn)
		}
		seen[tn] = name
		ot := ont.ObjectTypes[name]
		doc(&b, "", ot.DisplayName, "Primary key: "+ot.PrimaryKey+".")
		fmt.Fprintf(&b, "export interface %sProperties {\n", tn)
		for _, pn := range ot.PropertyOrder {
			p := ot.Properties[pn]
			if p.Type.Base == spec.TVector {
				continue // vectors are not returned by the query service
			}
			var notes []string
			if p.Sensitivity == spec.SensConfidential || p.Sensitivity == spec.SensRestricted {
				notes = append(notes, fmt.Sprintf("%s: null when your clearance is lower.", p.Sensitivity))
			}
			if p.Type.Base == spec.TDecimal {
				notes = append(notes, "Exact decimal as a string.")
			}
			if p.Type.Base == spec.TTimestamp {
				notes = append(notes, "RFC 3339 timestamp.")
			}
			doc(&b, "  ", notes...)
			fmt.Fprintf(&b, "  %s: %s | null;\n", key(pn), tsType(ont, p.Type, p.Constraints, p.ValueType))
		}
		b.WriteString("}\n")
		navs := ont.NavigationNames(name)
		linkType := "never"
		if len(navs) > 0 {
			linkType = union(navs)
		}
		fmt.Fprintf(&b, "export type %sLink = %s;\n", tn, linkType)
		fmt.Fprintf(&b, "export type %s = OntologyObject<%s, %sProperties>;\n\n", tn, quote(name), tn)
	}

	actions := sortedKeys(ont.ActionTypes)
	for _, name := range actions {
		at := ont.ActionTypes[name]
		an := typeName(strings.ToUpper(name[:1]) + name[1:])
		if prev, dup := seen[an+"Params"]; dup {
			return nil, fmt.Errorf("action types %q and %q map to the same TypeScript name %q", prev, name, an+"Params")
		}
		seen[an+"Params"] = name
		lines := []string{at.DisplayName, at.Description}
		for _, c := range at.SubmissionCriteria {
			if c.Message != "" {
				lines = append(lines, "Precondition: "+c.Message)
			}
		}
		doc(&b, "", lines...)
		fmt.Fprintf(&b, "export interface %sParams {\n", an)
		for _, pn := range at.ParamOrder {
			p := at.Parameters[pn]
			opt := "?"
			if p.Required && p.Default == nil {
				opt = ""
			}
			var t string
			switch p.Type.Kind {
			case spec.KindObjectRef:
				t = "PK"
				doc(&b, "  ", "Primary key of a "+p.Type.ObjectType+".")
			case spec.KindObjectRefList:
				t = "PK[]"
				doc(&b, "  ", "Primary keys of "+p.Type.ObjectType+" objects.")
			default:
				t = tsType(ont, spec.TypeRef{Base: p.Type.Base}, p.Constraints, p.ValueType)
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", key(pn), opt, t)
		}
		b.WriteString("}\n\n")
	}

	b.WriteString("export interface OntologyClient {\n  readonly objects: {\n")
	for _, name := range types {
		tn := typeName(name)
		fmt.Fprintf(&b, "    readonly %s: ObjectSet<%s, %sProperties, %sLink>;\n", key(name), quote(name), tn, tn)
	}
	b.WriteString("  };\n  readonly actions: {\n")
	for _, name := range actions {
		an := typeName(strings.ToUpper(name[:1]) + name[1:])
		fmt.Fprintf(&b, "    readonly %s: Action<%sParams>;\n", key(name), an)
	}
	b.WriteString("  };\n}\n\n")

	b.WriteString("/** Creates a typed client for this ontology. */\n")
	b.WriteString("export function createClient(options: ClientOptions): OntologyClient {\n")
	b.WriteString("  const t = new Transport(options, ONTOLOGY);\n  return {\n    objects: {\n")
	for _, name := range types {
		tn := typeName(name)
		fmt.Fprintf(&b, "      %s: new ObjectSet<%s, %sProperties, %sLink>(t, %s),\n", key(name), quote(name), tn, tn, quote(name))
	}
	b.WriteString("    },\n    actions: {\n")
	for _, name := range actions {
		an := typeName(strings.ToUpper(name[:1]) + name[1:])
		fmt.Fprintf(&b, "      %s: new Action<%sParams>(t, %s),\n", key(name), an, quote(name))
	}
	b.WriteString("    },\n  };\n}\n")
	return b.Bytes(), nil
}
